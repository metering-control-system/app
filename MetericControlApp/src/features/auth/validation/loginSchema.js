import * as z from 'zod';

export const loginSchema = z.object({
    password: z
        .string()
        .trim()
        .min(8, 'Пароль должен содержать минимум 8 символов')
        .regex(
            /^(?=.*[A-Za-z])(?=.*\d)[A-Za-z\d@$!%*?&]{8,}$/,
            'Пароль должен содержать хотя бы одну букву и цифру'
        ),
    login: z
        .string()
        .trim()
        .min(3, 'Пароль должен содержать минимум 3 символов')
        .max(20, 'Пароль должен содержать максимум 20 символов')
        .regex(
            /^[a-zA-Z0-9_]{3,20}$/,
            'Логин не должен содержать специсимволы'
        ),
});
